// Generates the built-in locations' height grids in packages/core/src/locations/data/.
// It downloads the Terrarium tiles for each location and runs the library's own pipeline on them,
// with the same settings as fetchLocation() and the playground. Run it once when a location changes:
//   node scripts/locations.mjs [id ...]
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { decodePng, encodeGrid16 } from './png16.mjs';

const root = new URL('../packages/core/src/locations/', import.meta.url);
const out = new URL('data/', root);

// The library modules are TypeScript, so bundle them for this script.
const bundled = await build({
  stdin: {
    contents: `export { LOCATIONS } from './builtin.ts'; export { buildLocation } from './fetch.ts'; export { TERRARIUM, terrariumMeters } from './pipeline.ts'; export { decodeGrid16 } from './png.ts';`,
    resolveDir: root.pathname, loader: 'ts',
  },
  bundle: true, write: false, format: 'esm', platform: 'node', logLevel: 'warning',
  // builtin.ts imports the data files lazily; they may not exist yet and are not needed here.
  plugins: [{ name: 'skip-data', setup(b) { b.onResolve({ filter: /\/data\// }, (a) => ({ path: a.path, external: true })); } }],
});
const lib = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

const chunkTypes = new Set();
async function readTile(z, x, y) {
  const url = lib.TERRARIUM.replace('{z}', z).replace('{x}', x).replace('{y}', y);
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${url} returned ${res.status}`);
      const png = decodePng(new Uint8Array(await res.arrayBuffer()));
      for (const t of png.chunks) chunkTypes.add(t);
      const m = new Float32Array(png.width * png.height);
      for (let i = 0; i < m.length; i++) m[i] = lib.terrariumMeters(png.rgba[i * 4], png.rgba[i * 4 + 1], png.rgba[i * 4 + 2]);
      return m;
    } catch (error) {
      if (attempt >= 4) throw error;
      await new Promise((r) => setTimeout(r, 500 * attempt));
    }
  }
}

const only = process.argv.slice(2);
mkdirSync(out, { recursive: true });
for (const location of lib.LOCATIONS) {
  if (only.length && !only.includes(location.id)) continue;
  const field = await lib.buildLocation(location.bbox, readTile);
  const png = encodeGrid16(field.samples, field.size);
  const back = await lib.decodeGrid16(new Uint8Array(png));
  let worst = 0;
  for (let i = 0; i < field.samples.length; i++) worst = Math.max(worst, Math.abs(back.samples[i] - Math.min(1, Math.max(0, field.samples[i]))));
  if (back.size !== field.size || worst > 1 / 65535) throw new Error(`${location.id}: the grid does not round-trip (${worst})`);
  const body = [
    `// Generated by scripts/locations.mjs from Terrarium tiles at zoom ${field.zoom} (${field.tiles} tiles). Do not edit.`,
    `// A ${field.size} × ${field.size} 16-bit greyscale PNG, north at the top, as base64.`,
    `export const minMeters = ${Math.round(field.minMeters * 10) / 10};`,
    `export const maxMeters = ${Math.round(field.maxMeters * 10) / 10};`,
    `export const zoom = ${field.zoom};`,
    // Typed as string, so the declaration file does not repeat the data.
    `const png: string = '${png.toString('base64')}';`,
    'export default png;',
    '',
  ].join('\n');
  writeFileSync(new URL(`${location.id}.ts`, out), body);
  console.log(`${location.id}: zoom ${field.zoom}, ${field.tiles} tiles, ${Math.round(field.minMeters)}–${Math.round(field.maxMeters)} m, ${(png.length / 1024).toFixed(1)} KB PNG`);
}
console.log(`tile chunks: ${[...chunkTypes].join(', ')}`);
