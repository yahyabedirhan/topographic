// Generates the built-in locations' height grids in packages/core/src/locations/data/.
// It downloads the Terrarium tiles for each location and runs the library's own pipeline on them,
// with the same settings as fetchLocation() and the playground. Run it once when a location changes:
//   node scripts/locations.mjs [id ...]
import { mkdirSync, writeFileSync } from 'node:fs';
import { encodeGrid16 } from './png16.mjs';
import { checkRoundTrip, loadPipeline, tileReader } from './terrarium.mjs';

const out = new URL('../packages/core/src/locations/data/', import.meta.url);
const lib = await loadPipeline();
const chunkTypes = new Set();
const readTile = tileReader(lib, chunkTypes);

const only = process.argv.slice(2);
mkdirSync(out, { recursive: true });
for (const location of lib.LOCATIONS) {
  if (only.length && !only.includes(location.id)) continue;
  const field = await lib.buildLocation(location.bbox, readTile);
  const png = encodeGrid16(field.samples, field.size);
  await checkRoundTrip(lib, location.id, field, png);
  const body = [
    `// Generated by scripts/locations.mjs from Terrarium tiles at zoom ${field.zoom} (${field.tiles} tiles). Do not edit.`,
    `// A ${field.size} × ${field.size} 16-bit greyscale PNG, north at the top, as base64.`,
    `export const minMeters = ${Math.round(field.minMeters * 10) / 10};`,
    `export const maxMeters = ${Math.round(field.maxMeters * 10) / 10};`,
    `export const zoom = ${field.zoom};`,
    // Typed as string, so the declaration file does not repeat the data.
    `const png: string = '${png.toString('base64')}';`,
    'export default png;',
    '',
  ].join('\n');
  writeFileSync(new URL(`${location.id}.ts`, out), body);
  console.log(`${location.id}: zoom ${field.zoom}, ${field.tiles} tiles, ${Math.round(field.minMeters)}–${Math.round(field.maxMeters)} m, ${(png.length / 1024).toFixed(1)} KB PNG`);
}
console.log(`tile chunks: ${[...chunkTypes].join(', ')}`);
